"""Compose a structured radiology-style report from analysis findings.

The report is assembled from the findings, not generated by a language model.
Every sentence maps to a measurement, so the report cannot say something the
engine did not measure. The mandatory non-clinical disclaimer is appended here
so it can never be omitted by a caller.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.engine.analyze import RANGE_BY_KEY, AnalysisResult, Finding

DISCLAIMER = (
    "This report was produced by an automated measurement tool for engineering "
    "demonstration purposes only. It is NOT a medical device, has NOT been "
    "validated for clinical use, and must NOT be used to diagnose, treat, or "
    "manage any patient. All findings require review by a qualified radiologist "
    "or physician."
)

# Order findings appear in the report body.
_REPORT_ORDER = (
    "cardiothoracic_ratio",
    "lung_density_left",
    "lung_density_right",
    "density_asymmetry",
    "costophrenic_density",
    "exposure_quality",
)


@dataclass
class ReportDraft:
    title: str
    impression: str
    findings_text: str
    technique: str
    disclaimer: str
    abnormal_count: int
    overall_confidence: float

    def as_dict(self) -> dict:
        return {
            "title": self.title,
            "impression": self.impression,
            "findings_text": self.findings_text,
            "technique": self.technique,
            "disclaimer": self.disclaimer,
            "abnormal_count": self.abnormal_count,
            "overall_confidence": round(self.overall_confidence, 4),
        }


def _format_value(finding: Finding) -> str:
    if finding.unit == "ratio":
        return f"{finding.value:.2f}"
    return f"{finding.value:.3f}"


def _format_range(finding: Finding) -> str:
    """Render the reference range. Ratios read better at 2 dp, densities at 3."""
    if finding.unit == "ratio":
        return f"{finding.ref_low:.2f}–{finding.ref_high:.2f}"
    return f"{finding.ref_low:.3f}–{finding.ref_high:.3f}"


def _breach_label(finding: Finding) -> str:
    """The human-readable breach label for a finding.

    Looked up from the reference-range table rather than stored on the finding,
    so the wording lives in exactly one place.
    """
    ref = RANGE_BY_KEY.get(finding.key)
    return ref.breach_label if ref else finding.label


def build_impression(result: AnalysisResult) -> str:
    """One-paragraph impression built from the flagged findings."""
    abnormal = [f for f in result.findings if f.flag != "normal"]
    if not abnormal:
        return (
            "No measured parameter falls outside its reference range. The cardiac "
            "silhouette, lung field densities, and costophrenic regions are all "
            "within expected limits on this film."
        )

    # Lead with the highest-confidence abnormal finding.
    ranked = sorted(abnormal, key=lambda f: f.confidence, reverse=True)
    lead = ranked[0]
    direction = "above" if lead.flag == "high" else "below"
    sentences = [
        f"{lead.label} measures {_format_value(lead)} ({lead.unit}), {direction} the "
        f"reference range of {_format_range(lead)} — {_breach_label(lead).lower()}."
    ]
    for extra in ranked[1:]:
        d = "above" if extra.flag == "high" else "below"
        sentences.append(
            f"{extra.label} is {d} range at {_format_value(extra)} " f"({_breach_label(extra).lower()})."
        )
    sentences.append("These are automated measurements and require radiologist correlation.")
    return " ".join(sentences)


def build_findings_text(result: AnalysisResult) -> str:
    """Line-by-line findings, one per measurement, in report order."""
    by_key = {f.key: f for f in result.findings}
    lines: list[str] = []
    for key in _REPORT_ORDER:
        finding = by_key.get(key)
        if finding is None:
            continue
        status = "NORMAL" if finding.flag == "normal" else finding.flag.upper()
        lines.append(
            f"{finding.label}: {_format_value(finding)} {finding.unit} "
            f"(ref {_format_range(finding)}) — {status} "
            f"[confidence {finding.confidence:.0%}]"
        )
    return "\n".join(lines)


def build_technique(result: AnalysisResult) -> str:
    q = result.quality
    parts = [
        f"Automated analysis of a {q.get('width', 0)}×{q.get('height', 0)} px " f"chest radiograph.",
        f"Mean film intensity {q.get('mean_intensity', 0):.3f}, "
        f"dynamic range {q.get('dynamic_range', 0):.3f}.",
        f"Image quality score {q.get('score', 0):.2f}.",
    ]
    issues = q.get("issues") or []
    if issues:
        parts.append(f"Quality flags: {', '.join(issues)}.")
    parts.append(f"Engine: {result.engine} v{result.engine_version}.")
    return " ".join(parts)


def build_report(result: AnalysisResult) -> ReportDraft:
    """Assemble the full report draft from an analysis result."""
    return ReportDraft(
        title="Chest Radiograph — Automated Measurement Report",
        impression=build_impression(result),
        findings_text=build_findings_text(result),
        technique=build_technique(result),
        disclaimer=DISCLAIMER,
        abnormal_count=result.abnormal_count,
        overall_confidence=result.overall_confidence,
    )
